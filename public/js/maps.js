import { TERRAIN } from "./terrain.js";

// Символы карты:
// "." равнина, "F" лес, "H" холмы, "W" вода, "M" горы,
// "C" нейтральный замок, "V" нейтральная деревня,
// "1"-"4" стартовые замки игроков, "a"-"d" стартовые деревни (a=1, b=2, c=3, d=4)
//
// Симметрия построена конструктивно:
//  - classic/cross (2 игрока, диагональная расстановка): поворот 180°.
//    Каждая нижняя строка = поворот соответствующей верхней (col -> size-1-col,
//    1<->2, a<->b, рельеф/нейтрали фиксированы). Только поворот даёт равные
//    расстояния диагональной паре игроков (горизонтальное зеркало — нет).
//  - corners/ring (2-4 игрока): зеркала по обеим осям -> орбита нейтрали = 4 клетки.
// Нейтралей мало: 2 замка + 2 деревни на 2-игровых картах, 4+4 на 4-игровых.
// Зданий нет в верхних рядах (0-2): верхняя панель HUD ничего не перекрывает.

// Равнина в terrain.js может называться PLAIN или GRASS - берём что есть
const PLAIN = TERRAIN.PLAIN !== undefined ? TERRAIN.PLAIN : TERRAIN.GRASS;

function charToTerrain(ch) {
  if (ch === "F") return TERRAIN.FOREST;
  if (ch === "H") return TERRAIN.HILL;
  if (ch === "W") return TERRAIN.WATER;
  if (ch === "M") return TERRAIN.MOUNTAIN;
  if (ch === "C" || (ch >= "1" && ch <= "4")) return TERRAIN.CASTLE;
  if (ch === "V" || (ch >= "a" && ch <= "d")) return TERRAIN.VILLAGE;
  return PLAIN;
}

