export function getMapById(id) {
  return MAPS.find(map => map.id === id) || MAPS[0];
}

// Разбирает ASCII-схему в данные игры
export function parseMap(mapDef) {
  const size = mapDef.rows.length;
  const terrain = [];
  const owners = [];
  const starts = {};

  for (let y = 0; y < size; y++) {
    const row = [];

    for (let x = 0; x < size; x++) {
      const char = mapDef.rows[y][x] || ".";
      row.push(CHAR_TO_TERRAIN[char] || TERRAIN.GRASS);

      const castleIndex = CASTLE_CHARS.indexOf(char);

      if (castleIndex !== -1) {
        const playerId = castleIndex + 1;
        starts[playerId] = { x, y };
        owners.push({ x, y, owner: playerId });
      }

      const villageIndex = VILLAGE_CHARS.indexOf(char);

      if (villageIndex !== -1) {
        owners.push({ x, y, owner: villageIndex + 1 });
      }

      if (char === "C" || char === "V") {
        owners.push({ x, y, owner: 0 });
      }
    }

    terrain.push(row);
  }

  return { size, terrain, owners, starts };
}