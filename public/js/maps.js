export function getMapById(id) {
  return MAPS.find(map => map.id === id) || MAPS[0];
}

// Разбор строк карты: рельеф + владельцы стартовых зданий + позиции стартов
export function parseMap(mapDef) {
  const size = mapDef.rows.length;
  const terrain = [];
  const owners = [];
  const starts = [];

  for (let y = 0; y < size; y++) {
    const row = [];

    for (let x = 0; x < size; x++) {
      const ch = mapDef.rows[y][x] || ".";
      row.push(charToTerrain(ch));

      if (ch >= "1" && ch <= "4") {
        const owner = Number(ch);
        owners.push({ x, y, owner });
        starts.push({ x, y, owner });
      } else if (ch >= "a" && ch <= "d") {
        owners.push({ x, y, owner: ch.charCodeAt(0) - 96 });
      }
    }

    terrain.push(row);
  }

  // ВАЖНО: старты строго по порядку владельцев + заглушка на индексе 0.
  // Модуль юнитов берёт старт по индексу, равному номеру игрока,
  // поэтому без заглушки юниты игрока 1 уезжали в угол игрока 2 и т.д.
  starts.sort((a, b) => a.owner - b.owner);
  starts.unshift({ x: -1, y: -1, owner: 0 });

  return { terrain, owners, starts, size };
}